package sqlite

import (
	"context"
	"database/sql"
	"fmt"
	"io/fs"
	"sort"
	"strings"
	"time"

	"github.com/alejandrogmota/scrumboard-api/migrations"
)

// Migrate applies every pending migration in order, inside one transaction
// each, and records what it applied.
//
// Two properties matter more than the mechanism, and migrate_test.go pins
// both: applying twice must be a no-op, because the container restarts more
// often than anyone plans for; and applying from an intermediate version must
// work, because that is the real production path.
func Migrate(ctx context.Context, db *sql.DB) error {
	if _, err := db.ExecContext(ctx, `
		CREATE TABLE IF NOT EXISTS schema_migrations (
			version    TEXT PRIMARY KEY,
			applied_at TEXT NOT NULL
		)`); err != nil {
		return fmt.Errorf("create schema_migrations: %w", err)
	}

	applied, err := appliedVersions(ctx, db)
	if err != nil {
		return err
	}

	files, err := migrationFiles()
	if err != nil {
		return err
	}

	for _, name := range files {
		version := strings.TrimSuffix(name, ".sql")
		if applied[version] {
			continue
		}
		body, err := migrations.FS.ReadFile(name)
		if err != nil {
			return fmt.Errorf("read migration %s: %w", name, err)
		}
		if err := applyMigration(ctx, db, version, string(body)); err != nil {
			return err
		}
	}
	return nil
}

func applyMigration(ctx context.Context, db *sql.DB, version, body string) error {
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin migration %s: %w", version, err)
	}
	defer tx.Rollback() //nolint:errcheck // no-op once committed

	for _, stmt := range splitStatements(body) {
		if _, err := tx.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("migration %s: %w\nstatement: %s", version, err, stmt)
		}
	}
	if _, err := tx.ExecContext(ctx,
		`INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)`,
		version, formatTime(time.Now()),
	); err != nil {
		return fmt.Errorf("record migration %s: %w", version, err)
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit migration %s: %w", version, err)
	}
	return nil
}

// MigrationVersions lists the embedded migrations in order, so a test can walk
// them one at a time.
func MigrationVersions() ([]string, error) {
	files, err := migrationFiles()
	if err != nil {
		return nil, err
	}
	out := make([]string, len(files))
	for i, f := range files {
		out[i] = strings.TrimSuffix(f, ".sql")
	}
	return out, nil
}

// MigrateTo applies migrations up to and including version, and no further.
// Only tests use it: production always goes to head.
func MigrateTo(ctx context.Context, db *sql.DB, version string) error {
	if _, err := db.ExecContext(ctx, `
		CREATE TABLE IF NOT EXISTS schema_migrations (
			version    TEXT PRIMARY KEY,
			applied_at TEXT NOT NULL
		)`); err != nil {
		return fmt.Errorf("create schema_migrations: %w", err)
	}
	applied, err := appliedVersions(ctx, db)
	if err != nil {
		return err
	}
	files, err := migrationFiles()
	if err != nil {
		return err
	}
	for _, name := range files {
		v := strings.TrimSuffix(name, ".sql")
		if applied[v] {
			continue
		}
		body, err := migrations.FS.ReadFile(name)
		if err != nil {
			return fmt.Errorf("read migration %s: %w", name, err)
		}
		if err := applyMigration(ctx, db, v, string(body)); err != nil {
			return err
		}
		if v == version {
			break
		}
	}
	return nil
}

func appliedVersions(ctx context.Context, db *sql.DB) (map[string]bool, error) {
	rows, err := db.QueryContext(ctx, `SELECT version FROM schema_migrations`)
	if err != nil {
		return nil, fmt.Errorf("read schema_migrations: %w", err)
	}
	defer rows.Close()

	applied := map[string]bool{}
	for rows.Next() {
		var v string
		if err := rows.Scan(&v); err != nil {
			return nil, err
		}
		applied[v] = true
	}
	return applied, rows.Err()
}

func migrationFiles() ([]string, error) {
	entries, err := fs.ReadDir(migrations.FS, ".")
	if err != nil {
		return nil, fmt.Errorf("read migrations directory: %w", err)
	}
	var out []string
	for _, e := range entries {
		// atlas.sum is Atlas's integrity file, not something to execute.
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		out = append(out, e.Name())
	}
	// Atlas names files with a sortable timestamp prefix, so lexical order is
	// chronological order.
	sort.Strings(out)
	return out, nil
}

// splitStatements cuts a migration into statements on semicolons at the end of
// a line, ignoring those inside string literals or trailing a comment.
//
// A full SQL parser would be the wrong tool here: these files are generated by
// Atlas from a schema this project controls, and the day one of them needs
// more than this is the day it should be reviewed by hand anyway.
func splitStatements(body string) []string {
	var (
		out     []string
		current strings.Builder
		inStr   bool
	)
	for _, line := range strings.Split(body, "\n") {
		trimmed := strings.TrimSpace(line)
		if !inStr && (trimmed == "" || strings.HasPrefix(trimmed, "--")) {
			continue
		}
		current.WriteString(line)
		current.WriteString("\n")

		if strings.Count(line, "'")%2 == 1 {
			inStr = !inStr
		}
		if !inStr && strings.HasSuffix(trimmed, ";") {
			stmt := strings.TrimSpace(current.String())
			if stmt != "" {
				out = append(out, stmt)
			}
			current.Reset()
		}
	}
	if stmt := strings.TrimSpace(current.String()); stmt != "" {
		out = append(out, stmt)
	}
	return out
}
